  String clockAnnouncement(DateTime now) {
    final hour12 = now.hour % 12 == 0 ? 12 : now.hour % 12;
    final minute = now.minute;

    if (minute == 0) {
      return '$hour12 മണി.';
    }

    return '$hour12 മണി $minute മിനിറ്റ്.';
  }

